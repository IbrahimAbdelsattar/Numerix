import { FileText, Loader2 } from "lucide-react";
import { useState } from "react";
import type { SolverResult } from "../hooks/useSolver";
import { toast } from "sonner";

interface Props { result: SolverResult; }

export function PdfExport({ result }: Props) {
  const [busy, setBusy] = useState(false);

  const generate = async () => {
    setBusy(true);
    try {
      const { default: jsPDF } = await import("jspdf");
      const doc = new jsPDF();
      const method = result.kind === "root" ? result.data.method : result.data.method;
      const now = new Date().toLocaleDateString();

      // Header
      doc.setFontSize(18);
      doc.setTextColor(59, 130, 246);
      doc.text("NumeriX Solution Sheet", 20, 20);
      doc.setFontSize(12);
      doc.setTextColor(100);
      doc.text(`${method} — ${now}`, 20, 28);

      doc.setDrawColor(59, 130, 246);
      doc.line(20, 32, 190, 32);

      let y = 40;
      doc.setTextColor(0);
      doc.setFontSize(11);

      if (result.kind === "root") {
        const d = result.data;
        doc.setFontSize(13);
        doc.text("Result", 20, y); y += 8;
        doc.setFontSize(11);
        doc.text(`Root: ${d.root?.toFixed(8) ?? "N/A"}`, 25, y); y += 6;
        doc.text(`Status: ${d.status}`, 25, y); y += 6;
        doc.text(`Iterations: ${d.totalIterations}`, 25, y); y += 6;
        doc.text(`Final |εₐ|: ${d.finalAbsError.toExponential(4)}`, 25, y); y += 6;
        doc.text(`Final |εᵣ|: ${d.finalRelError.toExponential(4)}`, 25, y); y += 12;

        // Iteration table
        doc.setFontSize(13);
        doc.text("Iteration Table", 20, y); y += 8;
        doc.setFontSize(8);

        const iters = d.iterations;
        const first = iters[0] as any;
        const isBracket = "xl" in first;
        const headers = isBracket
          ? ["n", "xl", "xu", "xr", "f(xr)", "|εₐ|"]
          : ["n", "xₙ", "xₙ₊₁", "|εₐ|", "|εᵣ|"];

        // Header row
        headers.forEach((h, i) => {
          doc.text(h, 25 + i * 30, y);
        });
        y += 5;

        for (const it of iters) {
          if (y > 270) { doc.addPage(); y = 20; }
          const row = isBracket
            ? [(it as any).n, (it as any).xl, (it as any).xu, (it as any).xr, (it as any).fxr, it.absError.toExponential(2)]
            : [(it as any).n, (it as any).xold ?? (it as any).x0, (it as any).xnew ?? (it as any).xnew, it.absError.toExponential(2), it.relError.toExponential(2)];
          row.forEach((v: any, i: number) => {
            doc.text(String(v), 25 + i * 30, y);
          });
          y += 4.5;
        }
      } else {
        const d = result.data;
        doc.setFontSize(13);
        doc.text("Solution", 20, y); y += 8;
        doc.setFontSize(11);
        if (d.solution) {
          d.solution.forEach((v, i) => {
            doc.text(`x${i + 1} = ${v.toFixed(6)}`, 25, y); y += 6;
          });
        }
      }

      // Footer
      doc.setFontSize(8);
      doc.setTextColor(150);
      doc.text("Generated by NumeriX — Numerical Analysis Virtual Lab", 20, 285);

      doc.save(`NumeriX_${method.replace(/\s+/g, "_")}_${now.replace(/\//g, "-")}.pdf`);
      toast.success("PDF downloaded!");
    } catch (e: any) {
      toast.error("PDF generation failed: " + e.message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <button onClick={generate} disabled={busy}
      className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-white/10 text-xs text-muted-foreground hover:text-foreground hover:bg-white/[0.04] disabled:opacity-50 transition">
      {busy ? <Loader2 className="w-3 h-3 animate-spin" /> : <FileText className="w-3 h-3" />}
      Export PDF
    </button>
  );
}
